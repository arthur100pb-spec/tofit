const registered = await agent.post('/api/auth/register').send({ name:'Teste Automatizado', email:`teste${stamp}@tofit.local`, password:'SenhaSegura123' }).expect(201);
const products = await agent.get('/api/products').expect(200);
const detail = await agent.get(`/api/products/${products.body.products[0].id}`).expect(200);
const cart = await agent.post('/api/cart').send({ variantId:detail.body.product.variants[0].id, quantity:1 }).expect(201);
const order = await agent.post('/api/orders').send({ shippingName:'Teste Automatizado', shippingPhone:'82999999999', shippingAddress:'Rua de Teste, 123, Maceió AL' }).expect(201);
const orders = await agent.get('/api/orders').expect(200);
const adminAgent = request.agent(app);
await adminAgent.post('/api/auth/login').send({ email:'admin-test@tofit.local', password:'SenhaAdminTeste123' }).expect(200);
const adminSummary = await adminAgent.get('/api/admin/summary').expect(200);
console.log(JSON.stringify({ health:health.body, user:registered.body.user.email, products:products.body.products.length, cartCount:cart.body.cart.count, orderId:order.body.orderId, orders:orders.body.orders.length, adminOrders:adminSummary.body.counts.orders },null,2));
